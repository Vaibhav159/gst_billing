test('purchase uses the actual decoded editor interface and refreshes changed supplier before applying permitted batch fields', async () => {
  const original = row(); original.read!.lines = [{ ...original.read!.lines[0], amount_only: true, quantity: null, rate: null, taxable: '123.45' }];
  let finish!: () => void;
  const { apply, calls } = setup(original, { 'GET suppliers/22/': () => new Promise(resolve => { finish = () => resolve({ status: 200, data: { supplier } }); }) });
  expect(editor.props?.initial.lines[0].taxable).toBe('123.45');
  expect(editor.props?.read?.lines[0].taxable).toBe(12345);
  expect(editor.props?.initial.supplier).toBe(21);
  expect(editor.props?.onSaved).toBeTypeOf('function');
  editor.body = body(); fireEvent.click(screen.getByRole('button', { name: 'Use these changes' }));
  await waitFor(() => expect(finish).toBeTypeOf('function'));
  expect(apply).not.toHaveBeenCalled(); finish();
  await waitFor(() => expect(apply).toHaveBeenCalledTimes(1));
  const next = apply.mock.calls[0][0];
  expect(next.file).toBe(original.file); expect(next.url).toBe(original.url);
  expect(next.read.supplier).toEqual({ id: supplier.id, name: supplier.name, gst_number: supplier.gst_number, state_code: supplier.state_code, city: supplier.city });
  expect(next).toMatchObject({ partyId: 22, partyResolved: true, itcEligible: false, itcMonth: '2026-11', buyerAck: true });
  expect(next.read).toMatchObject({ invoice_number: '0009/A', lines: [{ taxable: '123.45', amount_only: true, quantity: null, rate: null, gst_percent: '0.25' }] });
  const payload = bodyFor([next], 'purchases', firms).bills[0];
  expect(payload).toMatchObject({ supplier: 22, invoice_number: '0009/A', itc_month: '2026-11', lines: [{ taxable: '123.45', amount_only: true }] });
  for (const key of ['capture', 'duplicate_ok', 'needs_review']) expect(payload).not.toHaveProperty(key);
  expect(calls.every(call => call.method === 'GET')).toBe(true);
  expect(original.read!.invoice_number).toBe('UBS/26-27/0866');
});

const editor = vi.hoisted(() => ({ props: null as PurchaseEditorProps | null, body: null as PurchaseInput | null }));
vi.mock('@/pages/purchases/form/PurchaseEditor', () => ({ PurchaseEditor: (props: PurchaseEditorProps) => { editor.props = props; return <button onClick={() => props.onReview?.(editor.body!)}>Use these changes</button>; } }));
function setup(value = row(), answers = {}) {
  const calls = serve(answers), apply = vi.fn(), close = vi.fn();
  mount([{ path: '/edit', element: <PhotoEditor row={value} onApply={apply} onClose={close} /> }], ['/edit']);
  return { calls, apply, close };
}
const body = (): PurchaseInput => ({ business: 3, supplier: 22, invoice_number: '0009/A', invoice_date: '2026-10-07', payment_mode: 'bank', itc_eligible: false, itc_month: '2026-11', buyer_gstin: firms[0].gstin, buyer_ack: true, capture: 99, needs_review: true, duplicate_ok: true, lines: [{ product_name: 'Scrap', hsn_code: '7112', gst_percent: '0.25', unit: 'gms', amount_only: true, taxable: '123.45', note: 'Amount only' }] });
